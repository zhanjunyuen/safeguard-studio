import { motion } from 'framer-motion';
import { useMemo, useState } from 'react';
import CompetencyRadar from '../components/Radar';
import Timeline from '../components/Timeline';
import { COMPETENCY_META } from '../data/blocks';
import { CHALLENGES } from '../data/challenges';
import { SEED_STUDENTS, simulateStudent } from '../data/seedClass';
import { averageScores, DIMS, profileChallenge, type ChallengeProfile, type Dim } from '../engine/profile';
import { useSession } from '../store/session';

const heat = (v: number | null) =>
  v === null ? 'bg-slate-50 text-slate-400' : v >= 80 ? 'bg-emerald-100 text-emerald-900' : v >= 45 ? 'bg-amber-100 text-amber-900' : 'bg-rose-100 text-rose-900';

interface Row {
  name: string;
  live?: boolean;
  profile: ChallengeProfile;
}

export default function Teacher() {
  const [cid, setCid] = useState(CHALLENGES[0].id);
  const live = useSession((s) => s.progress[cid]);
  const [sel, setSel] = useState<string | null>(null);

  const rows: Row[] = useMemo(() => {
    const seeded = SEED_STUDENTS.map((s, i) => ({ name: s.name, profile: profileChallenge(cid, simulateStudent(s, cid, i)) }));
    const me = live?.attempts.length ? [{ name: 'You (live)', live: true, profile: profileChallenge(cid, live) }] : [];
    return [...me, ...seeded];
  }, [cid, live]);

  const selected = rows.find((r) => r.name === sel) ?? null;
  const n = rows.length;

  const firstAvg = averageScores(rows.map((r) => r.profile.anticipated));
  const nowAvg = averageScores(rows.map((r) => r.profile.current));
  const missedFirst = (d: Dim) => rows.filter((r) => (r.profile.anticipated?.[d] ?? 100) < 100).length;
  const miscCounts = new Map<string, number>();
  rows.forEach((r) => r.profile.misconceptions.forEach((m) => miscCounts.set(m, (miscCounts.get(m) ?? 0) + 1)));
  const topMisc = [...miscCounts.entries()].sort((a, b) => b[1] - a[1]);
  const refl = rows.map((r) => r.profile.reflectionAccuracy).filter((v): v is number => v !== null);
  const reflAvg = refl.length ? Math.round(refl.reduce((a, b) => a + b, 0) / refl.length) : null;
  const mostMissed = (['verification', 'privacy', 'integrity', 'bias'] as Dim[]).sort((a, b) => missedFirst(b) - missedFirst(a))[0];

  return (
    <div className="max-w-[1400px] mx-auto px-4 py-8" data-testid="teacher">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <div className="text-xs font-extrabold uppercase tracking-wider text-violet-600">Teacher dashboard · 8B Computing</div>
          <h1 className="text-4xl font-extrabold">Class AI literacy</h1>
          <p className="text-indigo-900/70">Scores are generated by running each student’s actual helpers against the hidden tests. Click a student to see how they got there.</p>
        </div>
        <div className="flex gap-1 bg-white rounded-full p-1 border-2 border-indigo-100">
          {CHALLENGES.map((c) => (
            <button key={c.id} onClick={() => { setCid(c.id); setSel(null); }} className={`px-3 py-1.5 rounded-full text-sm font-bold ${cid === c.id ? 'bg-indigo-950 text-white' : 'hover:bg-indigo-50'}`}>
              {c.emoji} {c.title}
            </button>
          ))}
        </div>
      </div>

      <div className="grid md:grid-cols-4 gap-4 mt-6">
        <Insight title="Most missed on first try" value={`${COMPETENCY_META[mostMissed].icon} ${COMPETENCY_META[mostMissed].label}`} sub={`${missedFirst(mostMissed)}/${n} students didn’t anticipate it`} />
        <Insight title="Top misconception" value={topMisc[0] ? `${topMisc[0][1]} students` : 'None'} sub={topMisc[0]?.[0] ?? 'No repeated mistakes'} />
        <Insight title="Over-cautious builders" value={`${rows.filter((r) => r.profile.misconceptions.some((m) => m.startsWith('Over-cautious'))).length} students`} sub="Blocked harmless questions at some point" />
        <Insight title="Explain failures correctly" value={reflAvg !== null ? `${reflAvg}%` : '–'} sub="Class average. Shows reasoning, not guessing" dark />
      </div>

      <div className="grid xl:grid-cols-[1fr_420px] gap-6 mt-6">
        <div className="bg-white rounded-3xl border-2 border-indigo-100 overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="text-left text-[11px] uppercase tracking-wider text-indigo-900/50">
                <th className="px-4 py-3">Student</th>
                {DIMS.map((d) => <th key={d} className="px-2 py-3 text-center">{COMPETENCY_META[d].icon} {COMPETENCY_META[d].label.split(' ')[0]}</th>)}
                <th className="px-2 py-3 text-center">Runs</th>
                <th className="px-2 py-3 text-center">Explains</th>
                <th className="px-4 py-3">Flags</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => (
                <tr
                  key={r.name}
                  onClick={() => setSel(r.name)}
                  className={`border-t border-indigo-50 cursor-pointer transition ${sel === r.name ? 'bg-violet-50' : 'hover:bg-indigo-50/50'} ${r.live ? 'font-extrabold' : ''}`}
                  data-testid={r.live ? 'row-live' : undefined}
                >
                  <td className="px-4 py-2.5 whitespace-nowrap">
                    {r.live && <span className="inline-block w-2 h-2 rounded-full bg-emerald-500 mr-2 animate-pulse" />}
                    {r.name}
                  </td>
                  {DIMS.map((d) => {
                    const v = r.profile.current?.[d] ?? null;
                    const f = r.profile.anticipated?.[d] ?? null;
                    return (
                      <td key={d} className="px-1.5 py-1.5 text-center">
                        <div className={`rounded-lg py-1 font-extrabold ${heat(v)}`}>
                          {v ?? '–'}
                          {f !== null && v !== null && f !== v && <div className="text-[10px] font-bold opacity-70">from {f}</div>}
                        </div>
                      </td>
                    );
                  })}
                  <td className="px-2 text-center">{r.profile.attempts}</td>
                  <td className="px-2 text-center">{r.profile.reflectionAccuracy ?? '–'}{r.profile.reflectionAccuracy !== null && '%'}</td>
                  <td className="px-4 py-2 text-xs">
                    <div className="flex flex-wrap gap-1">
                      {r.profile.misconceptions.slice(0, 2).map((m) => (
                        <span key={m} className="px-1.5 py-0.5 rounded bg-amber-50 text-amber-800 whitespace-nowrap max-w-[220px] truncate" title={m}>⚠️ {m}</span>
                      ))}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <aside className="bg-white rounded-3xl border-2 border-indigo-100 p-5 self-start xl:sticky xl:top-4">
          {selected ? (
            <motion.div key={selected.name} initial={{ opacity: 0, x: 10 }} animate={{ opacity: 1, x: 0 }}>
              <div className="text-xs font-extrabold uppercase tracking-wider text-violet-600">Student drill-down</div>
              <h2 className="text-2xl font-extrabold">{selected.name}</h2>
              <CompetencyRadar
                first={selected.profile.anticipated ? averageScores([selected.profile.anticipated]) : null}
                now={averageScores([selected.profile.current])}
                height={250}
              />
              {selected.profile.misconceptions.length > 0 && (
                <div className="rounded-2xl bg-amber-50 p-3 text-sm mb-2">
                  <div className="font-extrabold text-amber-900">Misconceptions to address</div>
                  <ul className="list-disc pl-5 text-amber-900/90">{selected.profile.misconceptions.map((m) => <li key={m}>{m}</li>)}</ul>
                </div>
              )}
              <Timeline profile={selected.profile} />
            </motion.div>
          ) : (
            <div>
              <div className="text-xs font-extrabold uppercase tracking-wider text-violet-600">Class overview</div>
              <h2 className="text-xl font-extrabold">Anticipated vs after fixing</h2>
              <CompetencyRadar first={firstAvg} now={nowAvg} height={280} firstLabel="Class first try" nowLabel="Class now" />
              <p className="text-sm text-indigo-900/70">The gap between the shapes is what students <b>learned by failing</b>. Select a student for their journey.</p>
            </div>
          )}
        </aside>
      </div>
    </div>
  );
}

function Insight({ title, value, sub, dark }: { title: string; value: string; sub: string; dark?: boolean }) {
  return (
    <div className={`rounded-3xl p-5 ${dark ? 'bg-indigo-950 text-white' : 'bg-white border-2 border-indigo-100'}`}>
      <div className={`text-xs uppercase tracking-wider font-extrabold ${dark ? 'text-indigo-200' : 'text-indigo-900/50'}`}>{title}</div>
      <div className="font-display text-2xl font-extrabold mt-1 leading-tight">{value}</div>
      <div className={`text-sm mt-1 ${dark ? 'text-indigo-100/80' : 'text-indigo-900/70'}`}>{sub}</div>
    </div>
  );
}
