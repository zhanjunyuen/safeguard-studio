/**
 * Copies the marking codebook text into the Edge Function, so the server builds exactly the prompt
 * the marking model was trained on (scripts/marking-data/prompt.ts). Re-run after editing
 * docs/marking-codebook.md:
 *
 *   npx vite-node scripts/sync-ai-prompt.ts
 *
 * src/engine/aiPrompts.test.ts fails if the copy is out of date.
 */
import { writeFileSync } from 'node:fs';
import { GENERAL, SECTION } from './marking-data/prompt';
import { CRITERION_NAME, RUBRIC_VERSION } from '../src/engine/marking';

const out = new URL('../supabase/functions/literacy-ai/promptData.js', import.meta.url).pathname;
writeFileSync(out, `// Generated by scripts/sync-ai-prompt.ts from docs/marking-codebook.md. Do not edit by hand.
export const RUBRIC_VERSION = ${JSON.stringify(RUBRIC_VERSION)};
export const CRITERION_NAME = ${JSON.stringify(CRITERION_NAME, null, 2)};
export const GENERAL = ${JSON.stringify(GENERAL)};
export const SECTION = ${JSON.stringify(SECTION, null, 2)};
`);
console.log('Wrote', out);
